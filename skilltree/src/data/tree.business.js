/*
 * tree.business.js — Freelance & Business.
 *
 * Twenty-one skills covering the work that turns a craft into an income:
 * deciding what you sell, finding people who want it, quoting, contracting,
 * delivering, getting paid, and doing it again without burning out.
 *
 * This tree exists because a goal like "open a web design business" is half
 * craft and half business, and the app could previously only answer the craft
 * half. The programme builder (domain/goals.js) draws from both, so that goal
 * produces a path through HTML and CSS *and* through pricing and contracts —
 * which is what actually stands between someone and a first paid project.
 *
 * How it grades. There is no sandbox for "sent a proposal", so like the
 * calisthenics tree this is self-attested against written standards — and the
 * standards are the useful part. "Found a client" is vague; "had a paid
 * conversation with someone you did not already know" is a thing you either
 * did or did not do. Every checklist item here is an observable action rather
 * than a feeling of readiness.
 *
 * On advice: contracts, tax and company structure are jurisdiction-specific
 * and this is not legal or financial advice. The skills here teach what the
 * questions are and why they matter, and say plainly where to get a real
 * answer.
 */

