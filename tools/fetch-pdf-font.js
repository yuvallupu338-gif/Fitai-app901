#!/usr/bin/env node
/*
 * fetch-pdf-font.js — downloads Assistant as TrueType and writes it into
 * portfolio/src/pdf/font.assistant.js as base64.
 *
 * The app's own PDF writer embeds a font, and it cannot embed the one the app
 * displays: `src/styles/fonts.css` carries woff2, which is Brotli-compressed
 * and which a PDF reader cannot read. A PDF wants the raw sfnt. So this fetches
 * the same family in the format the file format actually takes.
 *
 * The trick is the user agent. Google Fonts decides the format from it, and a
 * modern browser string gets woff2 — which is why `tools/fetch-fonts.js` sends
 * one. An old Android string gets plain TTF, which is what this needs.
 *
 * The generated file is committed, like fonts.css, so neither the app nor the
 * single-file build ever needs the network: a portfolio has to turn into a PDF
 * on a train.
 *
 * Assistant is SIL OFL 1.1. The licence travels with the font, in the file.
 *
 * Usage: node tools/fetch-pdf-font.js
 */

import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(ROOT, 'portfolio/src/pdf/font.assistant.js');

const CSS_URL = 'https://fonts.googleapis.com/css2?family=Assistant:wght@400;700';

/* An Android 2.3 browser is old enough that Google serves it TrueType. */
const UA = 'Mozilla/5.0 (Linux; U; Android 2.3.7; en-us; Nexus One Build/FRF91) '
  + 'AppleWebKit/533.1 (KHTML, like Gecko) Version/4.0 Mobile Safari/533.1';

async function get(url, asBuffer) {
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`);
  return asBuffer ? Buffer.from(await res.arrayBuffer()) : res.text();
}

const css = await get(CSS_URL, false);
const faces = [...css.matchAll(/font-weight:\s*(\d+);[\s\S]*?url\((https:[^)]+)\)/g)]
  .map((m) => ({ weight: Number(m[1]), url: m[2] }));

if (faces.length !== 2) {
  throw new Error(`expected two faces in the stylesheet, got ${faces.length}`);
}

const loaded = [];
for (const face of faces) {
  const bytes = await get(face.url, true);
  /* 0x00010000 is the sfnt version of a TrueType file. Anything else here means
   * the user agent trick stopped working and we are about to embed a woff2 that
   * no PDF reader can open. */
  const magic = bytes.readUInt32BE(0);
  if (magic !== 0x00010000 && bytes.slice(0, 4).toString('latin1') !== 'true') {
    throw new Error(`weight ${face.weight}: not a TrueType file (magic 0x${magic.toString(16)})`);
  }
  loaded.push({ weight: face.weight, bytes });
  console.log(`  ${face.weight}: ${(bytes.length / 1024).toFixed(1)} KB`);
}
loaded.sort((a, b) => a.weight - b.weight);

/* Wrapped at a width a person can scroll past, and concatenated rather than
 * held on one 60,000-character line, which no editor enjoys. */
function asChunks(buffer) {
  const b64 = buffer.toString('base64');
  const lines = [];
  for (let i = 0; i < b64.length; i += 96) lines.push(b64.slice(i, i + 96));
  return lines.map((l, i) => `  ${i ? '+ ' : ''}'${l}'`).join('\n');
}

const out = `/*
 * font.assistant.js — GENERATED by tools/fetch-pdf-font.js. Do not edit by hand.
 *
 * Assistant, regular and bold, as TrueType, base64. The app's PDF writer embeds
 * these into the file it produces: a PDF reader cannot read the woff2 the app
 * displays with, and a PDF with no embedded font cannot show Hebrew at all on a
 * machine that does not happen to have the same font installed.
 *
 * Assistant is licensed under the SIL Open Font License 1.1 — it may be
 * embedded in a document, which is exactly what happens here.
 *
 * Regenerate with: node tools/fetch-pdf-font.js
 */

export const ASSISTANT_400 =
${asChunks(loaded[0].bytes)};

export const ASSISTANT_700 =
${asChunks(loaded[1].bytes)};
`;

writeFileSync(OUT, out);
const kb = Math.round(Buffer.byteLength(out) / 1024);
console.log(`${OUT} — ${loaded.length} faces, ${kb} KB`);
