/*
 * exercises.legs.js — every lower-body movement in the library.
 *
 * Patterns owned by this file:
 *   squat, hinge, lunge, calf, plyo
 *
 * PROGRESSION FIELDS — per docs/CONTRACTS.md §2:
 *   regressionOf   id of the HARDER, canonical movement this variant is an
 *                  easier version of (null when nothing in the file is harder
 *                  in the same family).
 *   progressionTo  id of the NEXT rung up the ladder.
 * To walk a ladder downwards, reverse-look-up `progressionTo`.
 *
 * Ladders wired here:
 *   squat      sit-to-stand -> high box squat -> bodyweight squat ->
 *              tempo squat -> goblet -> back squat -> front squat
 *   pistol     single-leg box squat -> assisted pistol -> pistol
 *   hinge      dowel hinge drill -> band pull-through -> kettlebell deadlift ->
 *              dumbbell RDL -> barbell RDL -> conventional deadlift
 *   bridge     glute bridge -> single-leg bridge -> bodyweight hip thrust ->
 *              dumbbell hip thrust -> barbell hip thrust
 *   hamstring  band leg curl -> machine leg curl -> nordic lean ->
 *              band-assisted nordic -> nordic negative -> full nordic
 *              (the slider curl feeds in at the band-assisted rung)
 *   split      supported split squat -> split squat -> DB split squat -> bulgarian
 *   lunge      reverse lunge -> forward lunge -> walking lunge -> DB walking lunge
 *   step-up    low step-up -> knee-height step-up -> DB step-up
 *   calf       calf raise -> single-leg calf raise -> deficit calf raise
 *   plyo       pogo hop -> vertical jump -> low box jump -> box jump -> broad jump
 *
 * CONTRAINDICATIONS policy — this file is the one that decides whether a user
 * with a bad knee or a bad back gets a leg day at all, so the tags are narrow
 * and deliberate:
 *   'knee'        deep knee flexion UNDER LOAD (goblet/back/front squat, loaded
 *                 lunges, leg press/extension), kneeling drills (nordics), and
 *                 every landing.
 *   'lower_back'  axial spinal load (bar on the back) or a loaded bent-over
 *                 torso (deadlift, RDL, good morning, swing, back extension).
 *   'ankle'       loaded end-range dorsiflexion (deficit calf raise) and landings.
 *   'hip'         end-range hip flexion under load (full pistol only).
 * Unloaded hinging (dowel drill, bodyweight single-leg RDL), horizontally
 * loaded hinging (pull-throughs), bridges/hip thrusts, machine and band leg
 * curls and every supported or box-limited squat carry NO tag — those are the
 * options the generator hands an injured user, and they are genuinely safe.
 */

