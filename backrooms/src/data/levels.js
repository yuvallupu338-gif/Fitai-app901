/*
 * levels.js — Levels 0 through 99.
 *
 * A note on canon, because it matters and it is easy to be dishonest about.
 *
 * Levels 0 to 11 are the ones the community has documented consistently for
 * years — the Lobby's yellow rooms, the Habitable Zone's concrete, Pipe
 * Dreams, the Electrical Station, the Abandoned Office, the hotel, the dark,
 * the ocean, the caves, the suburbs, the wheat, the endless city — and they
 * are built here to match, along with the Poolrooms at 37, where they are
 * usually filed. Everything else in this file is this build's own work: the
 * numbers past 11 are not stable across sources, so rather than invent a
 * citation, these are written as original levels in the same voice, with the
 * same descent from "an office you cannot leave" to "somewhere that was never
 * an office at all". `canon: true` marks the ones that are not mine.
 *
 * Each level is a small pile of parameters over four systems: an archetype
 * from archetypes.js decides the architecture, a material kit decides what it
 * is made of, the fog and ambient decide how far you can see and what colour
 * the dark is, and the audio profile decides what it sounds like. The reason
 * a hundred levels fit in one file is that none of them contain any geometry.
 */

